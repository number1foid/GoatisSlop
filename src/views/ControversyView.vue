    <h1>Controversy</h1>

    <p>Most of what follows comes from a roughly hour-and-a-half documentary by the YouTuber Turkey Tom, which walks through Goatis' life and online career from his teenage years to the present day. It leans on old news articles, archived videos of Goatis himself, reviews from Airbnb hosts, screenshots, and a large number of testimonies from former partners, acquaintances and anonymous forum posters.</p>

