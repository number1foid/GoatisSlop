    <h2>The school incident (2006)</h2>

    <p>The story starts in Latvia. According to a 2006 Latvian news article cited in the video, a tenth-grade student named "Gatis L." lost control at his school and slashed at four schoolmates with a knife. The injuries were minor; all four were treated and sent home.</p>

    <p>Police quoted in the article put it down to past bullying and humiliation, and said the student had been fixated on a film about the Columbine shooting. Years later, British tabloids describing his stunts in the UK reported that he had a criminal record in Latvia over the incident.</p>

