    <h1>Ideology</h1>

    <p>Strip away the stunts and the controversies, and Goatis has a surprisingly consistent worldview. He has been building it, video by video, for over a decade. This page presents it the way a thoughtful supporter would: as charitably and coherently as possible.</p>

    <p class="note">This is a steel-man, not an endorsement. Many of the health claims below run directly against mainstream medicine. None of this is health advice.</p>

    <h2>Natural versus man-made</h2>

    <p>The core of everything Goatis says is one distinction: <em>natural</em> versus <em>man-made</em>.</p>

    <p>To him, "natural" is whatever a human would do guided by their senses and instincts. That means eating when hungry, resting when tired, and moving when there is a reason to. "Man-made" is everything that comes from abstract rules, symbols and imagination instead: money, jobs, clocks, borders, school, religion, sports rules, gyms, and food that has been bred, processed or cooked.</p>

    <p>The supporter's case goes like this. Most people are unhappy because they organise their lives around things that have no physical reality: grades, titles, salaries, schedules. Children live carefree, by instinct, and there is no law of nature that says adults must stop. The word "wild" literally means self-willed. A wild human, then, is a free one.</p>

    <blockquote>
      <p>"Instead of using your senses to see what's actually going on, you use your imagination."</p>
      <cite>Slavery Disguised as Society (2026)</cite>
    </blockquote>

    <p>This is his oldest theme. It appears in his 2013 video "Nature: What Is Unnatural?" and is still the backbone of his "Natural Human vs. Slave" videos today. In his early years he framed it in conspiracy language: the Illuminati, the New World Order, chemtrails. Since around 2019, that language has mostly given way to a broader philosophy of nature.</p>

    <h2>Raw animal foods</h2>

    <p>Goatis' diet follows directly from that philosophy. Humans, he argues, are predators. In nature they would eat other animals: their meat, organs, fat, blood and eggs, raw. He even objects to the phrase "raw meat": there is meat, and there is cooked meat.</p>

    <p>The reasoning is simple. An animal's body already contains everything a human body is built from, in a form humans can use. Organs are the most nutrient-dense of all, which is why, he points out, hunters have traditionally eaten them first and treated them as trophy food. Blood, in his words, is the best mineral supplement there is.</p>

    <blockquote>
      <p>"Meat has all the nutrients that we require and plants have nothing that we require."</p>
      <cite>Sv3rige &amp; Milk Jar vs. Vegan Gains &amp; Ask Yourself (2017)</cite>
    </blockquote>

    <p>He offers his own body as evidence. He reports steady energy, easy digestion, no bloating, and clearer skin since he switched.</p>

    <p>His views here have evolved. He tried cooked keto in 2015 and started on raw meat in February 2016, beginning with raw eggs. He then spent a period eating raw animal foods and no plants at all. Today he considers strict zero-carb unnatural too. His current position is raw animal foods plus some fruit and honey, eaten by instinct and by season.</p>

    <h2>Why cooking is the problem</h2>

    <p>If raw is natural, cooking is the original man-made sin. In a 2018 video he went as far as calling it "satanic", by which he means any act against nature.</p>

    <p>The supporter's case is that no wild animal cooks its food, and every organism avoids fire. Heat destroys vitamins and enzymes and creates new compounds, oxidised cholesterol among them, that the body has to deal with. Even people who cook implicitly admit this, he argues: everyone stops before the food turns to charcoal.</p>

    <p>He sees cooking as famine food that became a habit. Its browned, caramelised flavours, in his view, are what make it addictive.</p>

    <p>This even puts him at odds with fellow meat-eaters. He has dismissed the popular cooked "carnivore diet" as a trend that only removes part of what he calls the "slave diet".</p>

    <h2>Plants, seeds and fibre</h2>

    <p>Plants, in Goatis' view, don't want to be eaten, and they say so. Bitterness is a warning signal. Plants defend themselves chemically, with compounds that block mineral absorption or irritate the gut.</p>

    <p>Seeds are the worst offenders, because they are the plant's offspring and carry its strongest defences. To him, "seeds" covers grains, bread, nuts, legumes, coffee and cacao, the "toxic seeds" behind the dark chocolate clip on the Satire page. His evidence is that humans have to disguise the taste of grains and seeds with sugar, salt and additives before they find them edible at all.</p>

    <blockquote>
      <p>"Seeds are the most toxic food, it's not food, that humans consume nowadays."</p>
      <cite>Seeds: Why Most People Are Mentally Ill (2019)</cite>
    </blockquote>

    <p>Fibre gets similar treatment. It is, by definition, the part of the plant humans can't digest, so in his reasoning it adds bulk and gas, never nourishment.</p>

    <p>Fruit is the one partial exception. Its flesh is "meant" to be eaten: a plant wants its seeds spread. Humans also have an instinctive taste for sweetness. He eats fruit for hydration and sugar, but doesn't consider it a real food.</p>

    <h2>Health and medicine</h2>

    <p>Much of Goatis' thinking on health comes from Aajonus Vonderplanitz, the late founder of the "Primal Diet". He read Vonderplanitz's book in late 2016 and has called him the only person in decades who promoted something close to the natural human diet. He has also stressed that he was eating raw meat before he discovered him.</p>

    <p>From that tradition come his most contrarian claims:</p>

    <ul>
      <li>Bacteria are mostly beneficial; this is why he eats deliberately aged "high meat".</li>
      <li>Food poisoning is caused by toxins rather than germs.</li>
      <li>High cholesterol is protective, not dangerous.</li>
      <li>Cancer is a survival mechanism of the body.</li>
      <li>Vaccines, added salt and isolated supplements do more harm than good.</li>
    </ul>

    <p>The supporter's case is that mainstream medicine treats its foundations as settled faith rather than something to keep questioning. He asks critics for direct experimental proof that a given bacterium causes a given disease. Behind all of this sits his personal story: in 2015, after a vegan diet and an extreme fast, he ended up in hospital at around 43 kilograms, and he says it was raw animal food, not medicine, that rebuilt his body.</p>

    <h2>Exercise and the gym</h2>

    <p>To Goatis, exercise is stress, and stress wears the body down. Gyms are the clearest example of man-made living: in a typical title of his, lifting man-made metal in a man-made gym for no reason.</p>

    <blockquote>
      <p>"The less you do, the less you will age, because all exercise ages you."</p>
      <cite>Cold Showers &amp; Exercise (2018)</cite>
    </blockquote>

    <p>The supporter's case is that natural humans rest most of the day and move only with purpose: to hunt, travel or fight. If an activity always feels bad, the body is trying to tell you something. Muscle and health should come from nourishment, not from punishing the body into adapting.</p>

    <p>Even organised sport, boxing included, is to him a "domesticated" version of real instinct.</p>

    <h2>Work, school and "slavery"</h2>

    <p>If man-made life is unnatural, then the institutions that enforce it are a form of captivity. Goatis calls jobs slavery, school indoctrination, and modern people "slaves" who eat "slave food".</p>

    <blockquote>
      <p>"Jobs are imaginary. Money is also imaginary. None of this even matters."</p>
      <cite>What Your Life Should Look Like (2026)</cite>
    </blockquote>

    <p>He backs this with a sweeping history. Hunter-gatherers worked little. Elites have always kept the best food, meat and blood, for themselves while feeding grain to the masses. Each step since, from bread to organised religion to pasteurisation, seed oils and processed food, has tightened the chains.</p>

    <p>He presents himself as proof that you can opt out. By his own account, he hasn't had a job since July 2009.</p>

    <p>This lens has become his main one since around 2022, applied to fitness influencers, wealthy "slaves" and TikTok health trends alike.</p>

    <h2>Veganism</h2>

    <p>Veganism is the target that made Goatis famous, and it is the mirror image of everything above. If humans are natural predators, a vegan diet is, in his words, malnutrition that "cannot last".</p>

    <p>The supporter's case rests on nutrients that are only found in, or far more available from, animal foods: vitamin B12, and fat-soluble vitamins A, D and K2. It also rests on the large number of ex-vegans he interviewed in 2018 and 2019, and on his own five-month vegan period, which ended in hospital. He has said he never went vegan for ethical reasons. To him, veganism is a belief system, not a diet.</p>

    <p>His festival stunts were meant to make that point as bluntly as possible: in Amsterdam in 2018, and in Brighton and London in 2019. In his own framing, they showed "what humans eat in nature". In recent years, though, veganism has faded from his videos, replaced by the broader "natural versus slave" theme.</p>

    <h2>Morality and meaning</h2>

    <p>Goatis' naturalism extends to ethics, and this is where it is hardest to follow. He holds that there is no good and bad in nature, and that morality was invented by religions. In his view, revenge is natural and forgiveness is for the weak.</p>

    <p>Paradoxically, his philosophy also has an almost spiritual side. Since 2017 he has equated health with heaven: a nourished, natural life is a kind of ascension. Sungazing was central to his life between 2014 and 2017, and the sun once sat at the very top of his personal "food pyramid".</p>

    <blockquote>
      <p>"I wake up every day knowing that we are in heaven."</p>
      <cite>Reacting to TikTok Videos About Myself, Part 4 (2026)</cite>
    </blockquote>

    <p>Most recently, he has argued that natural nutrition also shapes the face: wide jaws, "hunter eyes" and good looks. He cites the dentist Weston A. Price for this, which brings him, ironically, into the territory of the looksmaxxing apps on the Satire page.</p>

    <h2>In short</h2>

    <p>Put charitably, Goatis' ideology is a radical, all-or-nothing version of a widespread modern intuition: that industrial life has made people sick, anxious and dependent, and that the way back runs through the body and its instincts.</p>

    <p>Where most people take that intuition as far as a farmers' market, he takes it all the way, to raw liver, no job and no doctor.</p>

