    <p>De redenering is eenvoudig. Het lichaam van een dier bevat al alles waaruit een menselijk lichaam is opgebouwd, in een vorm die mensen kunnen gebruiken. Organen zijn het allervoedzaamst, en daarom, zo merkt hij op, aten jagers die van oudsher als eerste en zagen ze die als trofeevoedsel. Bloed is volgens hem het beste mineralensupplement dat er bestaat.</p>

